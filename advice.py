SERVICE_OVERVIEW = """\
PrintBox - сервис самопечати через киоски (терминалы) в учебных корпусах.
Как это работает:
1. Юзер отправляет документ в основной Telegram-бот PrintBox.
2. Бот присылает 4-значный код (действует ~15 минут).
3. На экране киоска юзер вводит код, видит превью файла и настройки печати
   (цвет/ч-б, число копий, диапазон страниц, односторонняя/двусторонняя).
4. Подтверждает - появляется QR для оплаты Kaspi.
5. После оплаты (подтверждение приходит через Kaspi webhook) киоск автоматически печатает
   документ через SumatraPDF на подключённом принтере (Canon LBP722C и т.п.).
6. Если печать не началась или прервалась - возможны технические причины: сбой скачивания
   файла с сервера на ПК киоска, принтер не в сети, нет тонера/бумаги. Это можно проверить
   по нашим внутренним данным (SNMP-статус принтера, логи ПК) - именно так бот определяет,
   была ли реальная техническая ошибка, и стоит ли возвращать деньги.

Оплата - только Kaspi QR. Если деньги списались, а печать не вышла - это повод на возврат,
бот сам проверяет и либо возвращает деньги, либо передаёт сотруднику.
"""


def context_for(problem_type: str, document_status: str | None, document_found: bool | None) -> str:
    if problem_type == "upload_failed":
        if document_found is False:
            return KNOWLEDGE_BASE["upload_failed_no_document"]
        if document_status and document_status.lower() not in {"completed", "printed", "success"}:
            return KNOWLEDGE_BASE["upload_failed_error_status"]
        return ""
    if problem_type == "not_printed":
        return "\n".join(
            [
                KNOWLEDGE_BASE["not_printed_download_error"],
                KNOWLEDGE_BASE["not_printed_no_signal"],
                KNOWLEDGE_BASE["not_printed_signal_ok"],
            ]
        )
    return ""
